/**
 * Elige la postura de un ejercicio. `figureKey` viene de la biblioteca; si el
 * ejercicio es propio del entrenador se cae a la categoría, de modo que
 * cualquier ejercicio nuevo tiene ilustración desde el primer momento.
 */
export function poseFor(figureKey: string | null, category: ExerciseCategory): Pose {
  const key = (figureKey && POSE_BY_SLUG[figureKey]) || (figureKey as PoseKey | null);
  if (key && key in POSES) return POSES[key];
  return POSES[POSE_BY_CATEGORY[category] ?? 'generic'];
}
